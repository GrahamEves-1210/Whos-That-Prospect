// Generate pre-rendered silhouettes for every prospect, so the real headshot never reaches the
// browser until the game ends and nothing depends on CSS filters.
//
//   npm run silhouettes
//
// For each prospect it downloads the transparent ESPN headshot and writes two files to
// public/silhouettes/, named with a hash so the filename gives nothing away:
//   <hash>.png       solid black silhouette (the "Show silhouette" hint)
//   <hash>-blur.png  the same silhouette, heavily blurred (shown by default)
// It also writes src/data/silhouettes.ts mapping prospect id -> hash.
// Run it again whenever prospects are added or changed.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const OUT_DIR = path.join(ROOT, 'public', 'silhouettes');
const MAP_FILE = path.join(ROOT, 'src', 'data', 'silhouettes.ts');
const SALT = 'wtp-silhouette-v1';

// Read prospect ids and headshot URLs straight from the source file (no TS build needed).
const src = fs.readFileSync(path.join(ROOT, 'src', 'data', 'prospects.ts'), 'utf8');
const prospects = [...src.matchAll(/id:\s*'([^']+)'[\s\S]*?headshotUrl:\s*'([^']+)'/g)].map((m) => ({ id: m[1], url: m[2] }));
if (prospects.length === 0) throw new Error('No prospects with headshots found in prospects.ts');

fs.mkdirSync(OUT_DIR, { recursive: true });
for (const f of fs.readdirSync(OUT_DIR)) fs.unlinkSync(path.join(OUT_DIR, f));

const map = {};
for (const { id, url } of prospects) {
  const hash = crypto.createHash('sha256').update(SALT + id).digest('hex').slice(0, 16);
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${id}: headshot download failed (${res.status})`);
  const input = Buffer.from(await res.arrayBuffer());

  const { width, height } = await sharp(input).metadata();
  const alpha = await sharp(input).ensureAlpha().extractChannel('alpha').toBuffer();

  // Black everywhere, with the photo's own transparency as the mask.
  const silhouette = await sharp({ create: { width, height, channels: 3, background: '#000000' } })
    .joinChannel(alpha)
    .png({ compressionLevel: 9 })
    .toBuffer();
  fs.writeFileSync(path.join(OUT_DIR, `${hash}.png`), silhouette);

  // Blurred version: blur the mask so the shape softens, keep it black.
  const blurredAlpha = await sharp(alpha).blur(16).toBuffer();
  const blurred = await sharp({ create: { width, height, channels: 3, background: '#000000' } })
    .joinChannel(blurredAlpha)
    .png({ compressionLevel: 9 })
    .toBuffer();
  fs.writeFileSync(path.join(OUT_DIR, `${hash}-blur.png`), blurred);

  map[id] = hash;
  console.log(`${id} -> ${hash}`);
}

fs.writeFileSync(
  MAP_FILE,
  `// Generated by scripts/make-silhouettes.mjs. Do not edit by hand; run \`npm run silhouettes\`.\n` +
    `export const SILHOUETTES: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`,
);
console.log(`Wrote ${prospects.length} silhouettes to public/silhouettes and src/data/silhouettes.ts`);
